from typing import Any, Callable, Dict, List, Optional, Union 
from diffusers import StableDiffusionPipeline 
import torch 

class ExtendStableDiffusionPipeline(StableDiffusionPipeline): 
  "An extension of diffusers.StableDiffusionPipeline"
  def forward_collect_traj_ddim(
    self, 
    prompt = None, 
    height = None, 
    width = None,
    num_inference_steps = 50, 
    guidance_scale = 7.5, 
    negative_prompt = None, 
    num_images_per_prompt = 1, 
    eta = 1., 
    generator = None,
    latents = None, 
    prompt_embeds = None, 
    negative_prompt_embeds = None, 
    output_type = None, 
    return_dict = True, 
    callback = None, 
    callback_steps = 1, 
    cross_attention_kwargs = None, 
    is_ddp = False, 
    unet_copy = None, 
    soft_reward = False, 
  ): 
    """
    Args: 
      +) prompt (`str` or `List[str]`, *optional*) : The prompt or prompts to guide the image generation. If not 
      defined, please pass `prompt_embeds` instead. 
      +) height (`int`, *optional*, defaults to self.unet.config.sample_size * self.vae_scale_factor) : the 
      height in pixels of the generated image. 
      +) width (`int`, *optinal*, defaults to self.unet.config.sample_size * self.vae_scale_factor) : the 
      width in pixels of the generated image. 
      +) num_inference_steps (`int`, *optinal*, defaults to 50) : the number of denoising steps. More denoising 
      steps usually leads to higher quality image but the tradeoff is the inference time. 
      +) guidance_scale (`float`, *optinal*, defaults to 7.5) : guidance scale as defined in Classifer Free Guidance 
      (https://arxiv.org/abs/2207.12598). Guidance scale is enabled by setting `guidance_scale > 1`. Higher guidance 
      scale encourages to generate images that are closely linked to the text `prompt`, however the tradeoff are image 
      quality and sometimes diversity. 
      +) negative_prompt (`str` or `List[str]`, *optional*) : The prompt or prompts not to guide the image generation. 
      If not defined, please pass `negative_prompt_embeds` instead. Ignored when not using guidance. 
      +)  num_images_per_prompt (`int`, *optional*, defaults to 1) : the number of images to generate per prompt 
      +) eta (`float` *optional*, defaults to 0.0) : corresponds to parameter eta in the DDIM paper, i.e., the weight 
      of the noise in the backward process  
      +) latents (`torch.FloatTensor`, *optional*) : Pre-genrated noisy latents, sampled from a Gaussian distribution, 
      to be used as inputs for image generation. Can be used to tweak the same generation with different prompts. If
      not provided, a latents tensor will be re-generated by sampling using the supplied rng. 
      +) prompt_embeds (`torch.FloatTensor`, *optional*) : Pre-generated text embeddings. Can be used to easily tweak
      text inputs, *e.g* prompt weighting. If not provided, text embeddings will be generated from `prompt` input argument. 
      +) negative_prompt_embeds (`torch.FloatTensor`, *optional*) : Pre-generated negative text-embeddings. Can be used 
      to tweak text inputs, e.g. prompt_weighting. If not provided, negative_prompt_embeds will be generated from 
      `negative_prompt` input argument. 
      +) output_type (`str`, *optional*, defaults to `pil`) : the output format of the generated image (two options : `PIL.Image.image` 
      or `np.array`)
      +) return_dict (`bool`, *optional*, defaults to `True`): Whether or not to return a 
      [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] instead of a plain tuple.
      +) callback (`Callable`, *optional*): A function that will be called every `callback_steps` steps during 
      inference. The function will be called with the following arguments:
        `callback(step: int, timestep: int, latents: torch.FloatTensor)`.
      +) callback_steps (`int`, *optional*, defaults to 1): The frequency at which the `callback` function 
      will be called. If not specified, the callback will be called at every step.
      +) cross_attention_kwargs (`dict`, *optional*) : A kwargs dictionary that if specified is passed along to 
      the `AttnProcessor` as defined under `self.processor` in [diffusers.cross_attention]
      (https://github.com/huggingface/diffusers/blob/main/src/diffusers/models/cross_attention.py).
      +) is_ddp (`bool`, *optional*, defaults to `False`) : whether the unet is a `DistributedDataParallel` model. 
      if `true`, the `height` and `width` arguments will be calculated using the unwrapped model. 
      +) unet_copy (`torch.nn.Module`, *optional*, defaults to `None`) : the pretraine model to calculate 
      the soft_reward.
      +) soft_reward (`bool`, *optional*, defaults to `False`) : whether to use soft-reward
    
    Returns:
       +) [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] or
        `tuple`:
        [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] if
        `return_dict` is True, otherwise a `tuple.
        When returning a tuple, the first element is a list with the generated images, 
        and the second element is a list of `bool`s denoting whether the corresponding 
        generated image likely represents "not-safe-for-work" (nsfw) content, according 
        to the `safety_checker` 
       
       +) latents_list (`List[torch.FloatTensor]`): A list of latents states
       +) unconditional_prompt_embeds (`List[torch.FloatTensor]`) A list of unconditional prompt embeddings
       +) guided_prompt_embeds (`List[torch.FloatTensor]`) A list of conditional prompt embeddings
       +) log_probs_list (`List[torch.FloatTensor]`): A list of log probabilities for each step
       +) kl_path_list (`List[torch.FloatTensor]`): A list of soft rewards for each step
    """
    if is_ddp:
      height = height or self.unet.module.config.sample_size * self.vae_scale_factor
      width =  width or self.unet.module.config.sample_size * self.vae_scale_factor
    else:
      height = height or self.unet.config.sample_size * self.vae_scale_factor
      width = width or self.unet.config.sample_size * self.vae_scale_factor

    self.check_inputs(
      prompt = prompt, 
      height = height, 
      width = width,
      callback_steps = callback_steps, 
      negative_prompt = negative_prompt, 
      prompt_embeds = prompt_embeds, 
      negative_prompt_embeds = negative_prompt_embeds,  
    )

    if prompt is not None and isinstance(prompt, str): 
      batch_size = 1 
    elif prompt is not None and isinstance(prompt, list):
      batch_size = len(prompt) 
    else : 
      batch_size = prompt_embeds.shape[0] 
     
    device = self._execution_device 

    perform_classifier_guidance = guidance_scale > 1. 

    # Encode input prompt 
    prompt_embeds = self._encode_prompt(
      prompt = prompt, 
      device = device,
      num_images_per_prompt = num_images_per_prompt, 
      do_classifier_free_guidance = perform_classifier_guidance, 
      negative_prompt = negative_prompt, 
      prompt_embeds = prompt_embeds,
      negative_prompt_embeds = negative_prompt_embeds, 
    )

    # Prepare timesteps 
    self.scheduler.set_timesteps(num_inference_steps, device = device) 
    timesteps = self.scheduler.timesteps 
    
    # Prepare latent vars 

    if is_ddp : 
      num_channel_latents = self.unet.module.in_channels 
    else : 
      num_channel_latents = self.unet.in_channels 
    
    latents = self.prepare_latents(
      batch_size = batch_size * num_images_per_prompt, 
      num_channels_latents = num_channel_latents,
      height = height, 
      width = width, 
      dtype = prompt_embeds.dtype, 
      device = device, 
      generator = generator, 
      latents = latents 
    )

    latents_lst = [] 
    log_prob_lst = []

    latents_lst.append(latents.detach().clone().cpu())

    extra_step_kwargs = self.prepare_extra_step_kwargs(generator, eta) 
    num_warmup_steps = len(timesteps) - num_inference_steps * self.scheduler.order


    kl_lst = [] 

    with self.progress_bar(total = num_inference_steps) as progress_bar : 
      for index, time in enumerate(timesteps): 
        latent_model_input = torch.cat([latents] * 2 if perform_classifier_guidance else latents) 
        noise_prediction = self.unet(
          latent_model_input, 
          time, 
          encoder_hidden_states = prompt_embeds, 
          cross_attention_kwargs = cross_attention_kwargs, 
        ).sample 

        if soft_reward : 
          # \theta_{old} prediction
          old_noise_prediction = unet_copy(
            latent_model_input, 
            time, 
            encoder_hidden_states = prompt_embeds, 
            cross_attention_kwargs = cross_attention_kwargs, 
          ).sample 
          if perform_classifier_guidance : 
            old_noise_pred_uncond, old_noise_pred_cond = old_noise_prediction.chunk(2)
            old_noise_prediction = old_noise_pred_uncond + guidance_scale * (\
              old_noise_pred_cond - old_noise_pred_uncond)

        if perform_classifier_guidance : 
          noise_pred_uncond, noise_pred_cond = noise_prediction.chunk(2)
          noise_prediction = noise_pred_uncond + guidance_scale * (noise_pred_cond - noise_pred_uncond)
        unet_t = torch.tensor([time])[..., None, None, None].to(noise_prediction.device) 


        if soft_reward : 
          prev_latents = latents.clone() 

        latents, log_prob = self.scheduler.step_log_prob(
          noise_prediction, 
          unet_t, 
          latents, 
          **extra_step_kwargs, 
        )
        latents = latents.prev_sample 
        latents = latents.to(prompt_embeds.dtype)
        latents_lst.append(latents.detach().clone().cpu())
        log_prob_lst.append(log_prob.detach().clone().cpu())

        if soft_reward: 
          unet_times = torch.tensor([time] * noise_prediction.shape[0])[..., None, None, None].to(noise_prediction.device) 
  
          old_log_prob = self.scheduler.step_forward_log_prob(
            noise_prediction, 
            unet_times, 
            prev_latents, 
            latents, 
            **extra_step_kwargs, 
          ).detach().cpu() 

          kl_lst.append((log_prob - old_log_prob).detach().clone().cpu())
        
        if index == len(timesteps) - 1 or ((index + 1) > num_warmup_steps and (index + 1) % self.scheduler.order == 0): 
          progress_bar.update() 
          if callback is not None and index % callback_steps == 0: 
            callback(index, time, latents) 
        
    if output_type == 'latent': 
      image = latents 
    elif output_type == 'pil': 
      latents = latents.detach() 
      latents = latents.to(prompt_embeds.dtype) 
      image = self.decode_latents(latents) 

      image = self.numpy_to_pil(image)
    else : 
      image = self.decode_latents(latents) 

    if hasattr(self, "final_offload_hook") and self.final_offload_hook is not None:
      self.final_offload_hook.offload()

    unconditional_prompt_embeds, guided_prompt_embeds = prompt_embeds.chunk(2)

    if soft_reward: 
      kl_sum = 0. 
      kl_path = [] 
      for i in range(len(kl_lst)):
        kl_sum += kl_lst[i] 
      
      kl_path.append(kl_sum.clone())
      for i in range(1, len(kl_lst)):
        kl_sum = kl_sum - kl_lst[i - 1] 
        kl_path.append(kl_sum.clone())
    else : 
      kl_path = None 
    
    return (
      image,
      latents_lst, 
      unconditional_prompt_embeds.detach().cpu(), 
      guided_prompt_embeds.detach().cpu(), 
      log_prob_lst, 
      kl_path, 
    )

  def forward_calculate_log_prob(
    self, 
    prompt_embeds, 
    latents, 
    next_latents,
    time, 
    unet_copy = None, 
    height = None, 
    width = None, 
    num_inference_steps = 50, 
    guidance_scale = 7.5, 
    eta = 1., 
    generator = None,
    cross_attention_kwargs = None, 
    is_ddp = False, 
    soft_reward = False,    
  ): 
      
    """
    Args: 
      +) height (`int`, *optional*, defaults to self.unet.config.sample_size * self.vae_scale_factor) : the 
      height in pixels of the generated image. 
      +) width (`int`, *optinal*, defaults to self.unet.config.sample_size * self.vae_scale_factor) : the 
      width in pixels of the generated image. 
      +) num_inference_steps (`int`, *optinal*, defaults to 50) : the number of denoising steps. More denoising 
      steps usually leads to higher quality image but the tradeoff is the inference time. 
      +) guidance_scale (`float`, *optinal*, defaults to 7.5) : guidance scale as defined in Classifer Free Guidance 
      (https://arxiv.org/abs/2207.12598). Guidance scale is enabled by setting `guidance_scale > 1`. Higher guidance 
      scale encourages to generate images that are closely linked to the text `prompt`, however the tradeoff are image 
      quality and sometimes diversity. 
      +) eta (`float` *optional*, defaults to 0.0) : corresponds to parameter eta in the DDIM paper, i.e., the weight 
      of the noise in the backward process  
      +) latents (`torch.FloatTensor`, *optional*) : Pre-genrated noisy latents, sampled from a Gaussian distribution, 
      to be used as inputs for image generation. Can be used to tweak the same generation with different prompts. If
      not provided, a latents tensor will be re-generated by sampling using the supplied rng. (x_{t}) 
      +) next latents : next state (x_{t - 1})
      +) prompt_embeds (`torch.FloatTensor`, *optional*) : Pre-generated text embeddings. Can be used to easily tweak
      text inputs, *e.g* prompt weighting. If not provided, text embeddings will be generated from `prompt` input argument. 
      +) cross_attention_kwargs (`dict`, *optional*) : A kwargs dictionary that if specified is passed along to 
      the `AttnProcessor` as defined under `self.processor` in [diffusers.cross_attention]
      (https://github.com/huggingface/diffusers/blob/main/src/diffusers/models/cross_attention.py).
      +) is_ddp (`bool`, *optional*, defaults to `False`) : whether the unet is a `DistributedDataParallel` model. 
      if `true`, the `height` and `width` arguments will be calculated using the unwrapped model. 
      +) unet_copy (`torch.nn.Module`, *optional*, defaults to `None`) : the pretraine model to calculate 
      the soft_reward.
      +) soft_reward (`bool`, *optional*, defaults to `False`) : whether to use soft-reward
    
    Returns:
      log probability and KL regularizer 
    """

    if soft_reward : 
      unet_copy = None 

    if is_ddp:
      height = height or self.unet.module.config.sample_size * self.vae_scale_factor
      width =  width or self.unet.module.config.sample_size * self.vae_scale_factor
    else:
      height = height or self.unet.config.sample_size * self.vae_scale_factor
      width = width or self.unet.config.sample_size * self.vae_scale_factor

    device = self._execution_device 

    perform_classifier_guidance = guidance_scale > 1. 
    # Prepare timesteps 
    self.scheduler.set_timesteps(num_inference_steps, device = device) 
    timesteps = self.scheduler.timesteps 
    unet_times = timesteps[time] 

    latent_lst = []
    latent_lst.append(latents.detach().clone())

    extra_step_kwargs = self.prepare_extra_step_kwargs(generator, eta) 
    latent_model_input = torch.cat([latents] * 2) if perform_classifier_guidance else latents 
    time_model_input = torch.cat([unet_times] * 2) if perform_classifier_guidance else unet_times 

    noise_prediction = self.unet(
      latent_model_input, 
      time_model_input, 
      encoder_hidden_states = prompt_embeds, 
      cross_attention_kwargs = cross_attention_kwargs, 
    ).sample 

    if unet_copy is not None : 
      old_noise_prediction = unet_copy(
        latent_model_input, 
        time_model_input, 
        encoder_hidden_states = prompt_embeds, 
        cross_attention_kwargs = cross_attention_kwargs, 
      ).sample
      if perform_classifier_guidance : 
        old_noise_pred_uncond, old_noise_pred_cond = old_noise_prediction.chunk(2)
        old_noise_prediction = old_noise_pred_uncond + guidance_scale * (\
            old_noise_pred_cond - old_noise_pred_uncond)
    
    if perform_classifier_guidance : 
      noise_pred_uncond, noise_pred_cond = noise_prediction.chunk(2)
      noise_prediction = noise_pred_uncond + guidance_scale * (noise_pred_cond - noise_pred_uncond)
    
    if unet_copy is not None :
      kl_regularizer = (noise_prediction -old_noise_prediction) ** 2  
    else : 
      kl_regularizer = torch.zeros(noise_prediction.shape[0])
    
    unet_times = unet_times[..., None, None, None].to(noise_prediction.device) 

    log_prob = self.scheduler.step_forward_logprob( 
      noise_prediction, 
      unet_times, 
      latents, 
      next_latents, 
      **extra_step_kwargs
    )

    return log_prob, kl_regularizer 
    







